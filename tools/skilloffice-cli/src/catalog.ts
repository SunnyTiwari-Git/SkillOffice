import { existsSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { stringify } from 'yaml';
import { UserFacingError } from './errors.ts';
import { readSkillYaml } from './skill-yaml.ts';
import { findSkillFolders } from './validate.ts';

export interface CatalogEntry {
  id: string;
  summary: string;
  depends_on: string[];
  risk: string;
}

export interface Catalog {
  department: string;
  generated_at: string;
  skills: CatalogEntry[];
}

/** Builds the one-line-per-skill catalog a manager reads instead of every full skill. */
export function buildCatalog(departmentDir: string): Catalog {
  if (!existsSync(departmentDir)) throw new UserFacingError(`Department folder not found: ${departmentDir}`);
  const skills = findSkillFolders(departmentDir, ['.'])
    .map((dir) => readSkillYaml(dir))
    .filter((data) => data['kind'] === 'skill')
    .map((data) => ({
      id: String(data['id']),
      summary: String(data['summary']),
      depends_on: Array.isArray(data['depends_on']) ? data['depends_on'].map(String) : [],
      risk: String(data['risk']),
    }))
    .sort((a, b) => a.id.localeCompare(b.id));
  return { department: path.basename(path.resolve(departmentDir)), generated_at: new Date().toISOString(), skills };
}

export function writeCatalog(departmentDir: string): Catalog {
  const catalog = buildCatalog(departmentDir);
  const header = '# Generated by "skilloffice catalog". Do not edit by hand.\n';
  writeFileSync(path.join(departmentDir, 'catalog.yaml'), header + stringify(catalog));
  return catalog;
}
