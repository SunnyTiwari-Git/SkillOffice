import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { parse } from 'yaml';
import type { Catalog } from './catalog.ts';

interface RegistryDepartment {
  slug: string;
  name: string;
  status: string;
  manager?: string;
  scope?: string;
  boundaries?: string;
}

export const GUIDE_FILE = path.join('docs', 'departments.md');
const AVAILABLE = new Set(['pilot', 'active']);
const STATUS_WORDS: Record<string, string> = {
  pilot: 'Built and tested on Claude Code; second platform pending',
  active: 'Released',
};

function oneLine(text: string): string {
  return text.replace(/\s+/g, ' ').replace(/\|/g, '/').trim();
}

/** The short install code users can type, for example "fin". */
function installCode(manager: string): string {
  return manager.replace(/-manager$/, '');
}

/**
 * Builds the plain-English department guide from the registry and each department's catalog,
 * so the guide always matches what is actually built. Output is deterministic.
 */
export function buildDepartmentGuide(repoRoot: string): string {
  const registry = parse(readFileSync(path.join(repoRoot, 'registry', 'departments.yaml'), 'utf8')) as { departments: RegistryDepartment[] };
  const available = registry.departments.filter((item) => AVAILABLE.has(item.status) && item.manager);
  const upcoming = registry.departments.filter((item) => !AVAILABLE.has(item.status));

  const lines: string[] = [
    '# SkillOffice departments',
    '',
    '<!-- Generated by "skilloffice build" from registry/departments.yaml and each catalog.yaml. Do not edit by hand. -->',
    '',
    `SkillOffice has ${available.length} departments ready to install. Each one has a manager that plans the work, runs only the skills a request needs, fixes problems once and writes one report.`,
    '',
    'Install a department with its code, for example: `skilloffice install --platform claude-code --departments fin,legal`. See [Getting started](getting-started.md).',
    '',
    '| Code | Department | What it covers | Skills |',
    '| --- | --- | --- | --- |',
  ];

  const sections: string[] = [];
  for (const department of available) {
    const catalogFile = path.join(repoRoot, 'departments', department.slug, 'catalog.yaml');
    const catalog = existsSync(catalogFile) ? (parse(readFileSync(catalogFile, 'utf8')) as Catalog) : { department: department.slug, skills: [] };
    const code = installCode(department.manager as string);
    const anchor = department.slug.replace(/^\d+-/, '');
    lines.push(`| \`${code}\` | [${department.name}](#${anchor}) | ${oneLine(department.scope ?? '')} | ${catalog.skills.length} |`);

    sections.push(
      '',
      `<a id="${anchor}"></a>`,
      '',
      `## ${department.name}`,
      '',
      `Install code: \`${code}\` · Manager skill: \`${department.manager}\` · Status: ${STATUS_WORDS[department.status] ?? department.status}`,
      '',
      oneLine(department.scope ?? ''),
      ...(department.boundaries ? ['', `Not covered here: ${oneLine(department.boundaries)}`] : []),
      '',
      '| Skill | What it does |',
      '| --- | --- |',
      ...catalog.skills.map((skill) => `| \`${skill.id.split('/')[1]}\` | ${oneLine(skill.summary)} |`),
      '',
      `More detail: [${department.slug} README](../departments/${department.slug}/README.md)`,
    );
  }

  lines.push(...sections);
  if (upcoming.length > 0) {
    lines.push('', '## Coming later', '', ...upcoming.map((item) => `- ${item.name}`));
  }
  return `${lines.join('\n')}\n`;
}

export function writeDepartmentGuide(repoRoot: string): string {
  const file = path.join(repoRoot, GUIDE_FILE);
  writeFileSync(file, buildDepartmentGuide(repoRoot));
  return file;
}
